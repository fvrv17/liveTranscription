"""
Сценарии: те ситуации зала, на которых диаризация ломается.

Каждый сценарий — это один конкретный вопрос к системе, а не «ещё немного
разного аудио». Если сценарий не может провалиться, он ничего не проверяет
и его здесь быть не должно.
"""
from __future__ import annotations

from dataclasses import dataclass, field

from scenes import Scene, Voice, build, cast


def gain(v: Voice, db: float) -> Voice:
    """Тот же человек, другой микрофон. Имя в эталоне сохраняется."""
    return Voice(v.name, v.f0, v.env_db, gain_db=db)


@dataclass
class Scenario:
    scene: Scene
    enroll: list[str] = field(default_factory=list)   # кто записан на саундчеке
    asks: str = ""                                    # что именно проверяем


def build_all() -> list[Scenario]:
    V = cast()
    P = 0.9                       # пауза, гарантированно рвущая сегмент
    out: list[Scenario] = []

    # 1. Базовая панель: три различимых голоса, чёткие паузы. Провалиться тут
    #    нельзя — если провалилось, дело не в трудных случаях, а в основах.
    out.append(Scenario(
        build("panel", [
            ("Мария", 4.0), (None, P), ("Иван", 3.5), (None, P), ("Ольга", 3.0),
            (None, P), ("Мария", 3.0), (None, P), ("Иван", 2.5), (None, P), ("Ольга", 2.5),
        ], V, seed=1),
        enroll=["Мария", "Иван", "Ольга"],
        asks="три различимых голоса с саундчека — база, должно быть почти идеально"))

    # 2. Два похожих голоса. Косинус между ними 0.88 при пороге назначения
    #    0.68 — то есть по одному лишь порогу они неразличимы. Спасти может
    #    только отрыв от второго места: оба центроида известны с саундчека.
    out.append(Scenario(
        build("similar", [
            ("Мария", 4.0), (None, P), ("Марина", 3.5), (None, P), ("Иван", 3.0),
            (None, P), ("Мария", 3.0), (None, P), ("Марина", 3.0),
        ], V, seed=2),
        enroll=["Мария", "Марина", "Иван"],
        asks="Мария и Марина похожи (cos 0.88) — развести или честно промолчать"))

    # 3. Незаявленный участник: вышел из зала к микрофону, на саундчеке его
    #    не было. Система обязана завести новый кластер, а не приписать
    #    реплику ближайшему из панелистов.
    out.append(Scenario(
        build("late_joiner", [
            ("Мария", 4.0), (None, P), ("Иван", 3.5), (None, P), ("Мария", 3.0),
            (None, P), ("Ольга", 4.0), (None, P), ("Ольга", 3.0), (None, P), ("Мария", 2.5),
        ], V, seed=3),
        enroll=["Мария", "Иван"],
        asks="голос без энроллмента — новый кластер, а не чужая фамилия"))

    # 4. Короткие реплики. «Да», «согласен», «нет» — половина панельной
    #    дискуссии; они короче окна эмбеддинга, и на них легче всего либо
    #    промолчать, либо приписать их предыдущему говорившему.
    out.append(Scenario(
        build("backchannels", [
            ("Мария", 5.0), (None, 0.7), ("Иван", 0.5), (None, 0.7), ("Мария", 4.0),
            (None, 0.7), ("Иван", 0.6), (None, 0.7), ("Ольга", 0.5), (None, 0.7),
            ("Мария", 3.0),
        ], V, seed=4),
        enroll=["Мария", "Иван", "Ольга"],
        asks="реплики короче окна эмбеддинга"))

    # 5. Перепад уровней: петличка тише трибунного на 18 дБ. Эмбеддинг обязан
    #    быть инвариантен к гейну, иначе один человек распадётся на «громкого»
    #    и «тихого».
    G = {**V,
         "Мария_тихо": gain(V["Мария"], -18.0),
         "Иван_громко": gain(V["Иван"], 0.0),
         "Иван_тихо": gain(V["Иван"], -14.0)}
    out.append(Scenario(
        build("gain_mismatch", [
            ("Мария", 4.0), (None, P), ("Иван_громко", 3.5), (None, P),
            ("Мария_тихо", 3.5), (None, P), ("Иван_тихо", 3.0), (None, P),
            ("Мария", 2.5),
        ], G, seed=5),
        enroll=["Мария", "Иван"],
        asks="один человек на микрофонах с разницей 18 дБ — не должен распасться надвое"))

    # 6. Двое подряд без паузы. Сегментатор режет по паузам и про смену голоса
    #    не знает, поэтому реплики склеиваются в ОДИН сегмент. Один sid — одна
    #    метка, поэтому часть такого сегмента ошибочна неизбежно; проверяем,
    #    что система это замечает (change_at) и не завышает уверенность.
    out.append(Scenario(
        build("mid_segment", [
            ("Мария", 2.5), ("Иван", 2.5), (None, P), ("Ольга", 3.0),
            ("Мария", 2.5), (None, P), ("Иван", 3.0),
        ], V, seed=6),
        enroll=["Мария", "Иван", "Ольга"],
        asks="смена голоса внутри сегмента — поймать момент и срезать уверенность"))

    # 7. Главный сценарий для офлайн-прохода — и единственный, где онлайн
    #    обязан провалиться.
    #
    #    Саундчека нет (докладчиков не удалось собрать заранее), голоса Марии
    #    и Марины похожи. Первая же реплика Марины проходит порог назначения
    #    к кластеру Марии и вливается в него, утаскивая центроид на середину;
    #    дальше туда же попадает всё, что скажут обе. Онлайн этого не исправит
    #    никогда: у него нет ни второго шанса, ни причины усомниться.
    #
    #    Офлайн видит все реплики разом. Расстояние внутри одного голоса здесь
    #    ~0.01, между Марией и Мариной ~0.12 — на полной картине они делятся
    #    надёжно, хотя поштучно и последовательно неразделимы.
    #
    #    Проверка тут двойная: архив должен стать заметно лучше онлайна,
    #    а онлайн — остаться плохим. Сценарий, в котором онлайн внезапно
    #    справился сам, перестал проверять офлайн-проход (ровно это и
    #    случилось с прошлой версией сценария на шумной первой реплике:
    #    шум -12 дБ эмбеддинг почти не двигает, и склейки не происходило).
    out.append(Scenario(
        build("greedy_merge", [
            ("Мария", 3.5), (None, P), ("Марина", 3.5), (None, P), ("Иван", 3.0),
            (None, P), ("Мария", 3.5), (None, P), ("Марина", 3.0), (None, P),
            ("Иван", 3.0), (None, P), ("Марина", 3.0), (None, P), ("Мария", 3.0),
        ], V, seed=7),
        enroll=[],
        asks="жадность онлайна слила два похожих голоса — офлайн обязан разделить"))

    return out
