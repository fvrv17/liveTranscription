"""
Детерминированный энкодер голоса для eval.

Зачем он вообще нужен. ECAPA весит сотни мегабайт, тянет torch и хочет GPU —
в CI её не будет. Но ломается в диаризации не модель: ломается кластеризация,
оконное разбиение, отбор речи, склейка кластеров и перевод шкал времени.
Всё это ошибается одинаково независимо от того, кто считает вектор.

Поэтому здесь честная функция ОТ АУДИО, а не таблица «этот кусок = Мария».
Таблица проверяла бы только арифметику кластеризации и молча проходила бы
мимо ошибки в нарезке ленты: если резать не тот интервал, подменный энкодер
по таблице всё равно вернёт правильный вектор, а настоящий — мусор. Считая
спектр реального куска, мы ловим и это.

Устройство: усреднённый по кадрам спектр -> энергии в 32 лог-полосах -> log ->
вычитание среднего -> L2. Вычитание среднего в лог-области убирает
постоянный гейн, как это делают настоящие спикерские эмбеддинги: тот же голос
на петличке и на трибунном микрофоне должен давать один вектор.
"""
from __future__ import annotations

import numpy as np

SAMPLE_RATE = 16000
NFFT = 1024                # 64 мс: шаг по частоте 15.6 Гц, хватает на нижние форманты
N_BANDS = 32
N_CEPS = 20                # сколько коэффициентов оставляем после DCT
# Нижняя граница выше основного тона любого голоса. Полосы под f0 не получают
# гармоник вообще, дают log(~0) и одинаковый обрыв в векторе КАЖДОГО голоса —
# несколько таких общих координат тянут любой косинус к единице.
F_LO, F_HI = 250.0, 7000.0


class StubEncoder:
    """Спектральная огибающая куска."""

    def __init__(self, cfg=None):
        self.win = np.hanning(NFFT).astype(np.float32)
        freqs = np.fft.rfftfreq(NFFT, 1.0 / SAMPLE_RATE)
        edges = np.geomspace(F_LO, F_HI, N_BANDS + 1)

        # Полоса, в которую попал бин. Нижние лог-полосы уже шага сетки FFT,
        # и часть из них не получает НИ ОДНОГО бина. Такая полоса даёт
        # log(0) — одинаковую константу во всех векторах сразу; несколько
        # таких координат тянут любой косинус к единице, и разделимость
        # пропадает. Поэтому пустые полосы выбрасываем на этапе сборки.
        idx = np.digitize(freqs, edges) - 1
        ok = (idx >= 0) & (idx < N_BANDS)
        self._idx = idx[ok]
        self._ok = ok
        counts = np.bincount(self._idx, minlength=N_BANDS)
        self._keep = counts > 0
        self.dim = N_CEPS

        n_keep = int(self._keep.sum())
        k = np.arange(n_keep)[:, None]
        self._dct = np.cos(np.pi * k * (2 * np.arange(n_keep) + 1) / (2 * n_keep))
        # Лифтер. Кепстр естественно затухает как ~1/i, поэтому без него
        # направление вектора задаёт один c1 — общий наклон спектра, — и любые
        # два широкополосных голоса оказываются похожи. Линейный подъём
        # уравнивает вклад коэффициентов, и вектор начинает зависеть от ФОРМЫ
        # огибающей. Ровно ту же роль в боевых системах играет обучение
        # эмбеддинга: без декорреляции сырой спектр разделяет плохо.
        self._lifter = np.arange(1, N_CEPS + 1, dtype=np.float64)

    def encode(self, audio: np.ndarray) -> np.ndarray | None:
        n = (len(audio) // NFFT) * NFFT
        if n < NFFT:
            return None
        frames = audio[:n].reshape(-1, NFFT) * self.win
        spec = np.abs(np.fft.rfft(frames, axis=1)).mean(axis=0)
        band = np.bincount(self._idx, weights=spec[self._ok], minlength=N_BANDS)[self._keep]
        # c0 отбрасываем вместе с гейном: он и есть суммарная громкость куска.
        # Свёртка broadcasting'ом, а не matmul: BLAS-путь numpy сыплет здесь
        # ложными предупреждениями о переполнении на вполне конечных числах.
        ceps = (self._dct * np.log(band + 1e-8)).sum(axis=1)[1:N_CEPS + 1] * self._lifter
        norm = float(np.linalg.norm(ceps))
        return (ceps / norm).astype(np.float32) if norm > 1e-9 else None
